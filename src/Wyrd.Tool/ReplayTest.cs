using System.Globalization;
using System.Text;
using Wyrd.Runtime;

namespace Wyrd.Tool;

/// <summary>Turns a recorded instance history into a readable timeline or a regression test (Urd).</summary>
internal static class ReplayTest
{
    private static readonly string[] Usings = ["Wyrd.Runtime", "Wyrd.Testing", "Xunit"];

    public static string Generate(
        InstanceHistory history, string json, string runtime, string process, string @namespace, IEnumerable<string> usings, string source)
    {
        var name = Identifier(history.Process + " " + history.Key);
        var quotes = new string('"', Math.Max(3, LongestRun(json, '"') + 1));
        var text = new StringBuilder();
        text.AppendLine(CultureInfo.InvariantCulture, $"// Generated by `dotnet wyrd replay {source} --as-test`: {history.Process} '{history.Key}' must keep doing what it did.");
        foreach (var directive in Usings.Concat(usings).Distinct(StringComparer.Ordinal))
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"using {directive};");
        }

        text.AppendLine();
        text.AppendLine(CultureInfo.InvariantCulture, $"namespace {@namespace};");
        text.AppendLine();
        text.AppendLine(CultureInfo.InvariantCulture, $"public class {Pascal(name)}Replay");
        text.AppendLine("{");
        text.AppendLine(CultureInfo.InvariantCulture, $"    private const string History = {quotes}");
        foreach (var line in json.ReplaceLineEndings("\n").TrimEnd('\n').Split('\n'))
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"        {line}");
        }

        text.AppendLine(CultureInfo.InvariantCulture, $"        {quotes};");
        text.AppendLine();
        text.AppendLine("    [Fact]");
        text.AppendLine(CultureInfo.InvariantCulture, $"    public async Task {name}_replays_as_recorded() =>");
        text.AppendLine(CultureInfo.InvariantCulture, $"        (await Urd.ReplayAsync({runtime}, {process}, InstanceHistory.FromJson(History))).ThrowIfDiverged();");
        text.AppendLine("}");
        return text.ToString();
    }

    public static string Timeline(InstanceHistory history)
    {
        var text = new StringBuilder();
        text.AppendLine(CultureInfo.InvariantCulture, $"{history.Process} '{history.Key}' (structure {history.Fingerprint})");
        var start = history.Entries.Count > 0 ? history.Entries[0].At : default;
        foreach (var entry in history.Entries)
        {
            var at = (entry.At - start).ToString(@"hh\:mm\:ss", CultureInfo.InvariantCulture);
            var what = entry.Kind switch
            {
                HistoryKind.Sent => $"-> {Short(entry.Type)}{(entry.Compensating ? " (compensating)" : "")}{(entry.Attempt > 1 ? $" attempt {entry.Attempt}" : "")}",
                HistoryKind.Replied => $"{entry.Outcome?.ToLowerInvariant()}{(entry.Type is null ? "" : " " + Short(entry.Type))}",
                HistoryKind.Started => $"started by {Short(entry.Type)}",
                HistoryKind.Received => $"<- {Short(entry.Type)}",
                HistoryKind.Suspended => $"SUSPENDED: {entry.Reason}",
                HistoryKind.TimedOut => "timed out",
                HistoryKind.CompensationRequested => "compensation requested by an operator",
                HistoryKind.Resumed => "resumed by an operator",
                _ => entry.Kind.ToString().ToLowerInvariant(),
            };
            text.AppendLine(CultureInfo.InvariantCulture, $"[{at}] {what}");
        }

        return text.ToString();
    }

    /// <summary>The name a reader knows: the class for a CLR type name, the contract for an integration event.</summary>
    private static string Short(string? type) => type is null ? "" : type.Contains(' ', StringComparison.Ordinal) ? type : type.Split('.', '+')[^1];

    private static int LongestRun(string text, char c)
    {
        int longest = 0, current = 0;
        foreach (var ch in text)
        {
            current = ch == c ? current + 1 : 0;
            longest = Math.Max(longest, current);
        }

        return longest;
    }

    /// <summary>"OrderFulfillment A-1" → "order_fulfillment_a_1".</summary>
    private static string Identifier(string text)
    {
        var name = new StringBuilder();
        for (var i = 0; i < text.Length; i++)
        {
            var c = text[i];
            if (char.IsUpper(c) && i > 0 && char.IsLower(text[i - 1]))
            {
                name.Append('_');
            }

            name.Append(char.IsLetterOrDigit(c) ? char.ToLowerInvariant(c) : '_');
        }

        var collapsed = string.Join('_', name.ToString().Split('_', StringSplitOptions.RemoveEmptyEntries));
        return char.IsDigit(collapsed[0]) ? "_" + collapsed : collapsed;
    }

    private static string Pascal(string identifier) =>
        string.Concat(identifier.Split('_', StringSplitOptions.RemoveEmptyEntries).Select(part => char.ToUpperInvariant(part[0]) + part[1..]));
}
