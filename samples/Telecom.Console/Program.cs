using Telecom;
using Wyrd;
using Wyrd.Runtime;
using Wyrd.Testing;

if (args is ["--replay", var input])
{
    var recording = InstanceHistory.FromJson(await File.ReadAllTextAsync(input));
    (await Urd.ReplayAsync(TelecomModule.CreateRuntime, Flows.ProfileProvisioning, recording)).ThrowIfDiverged();
    Console.WriteLine("Recorded process replayed without divergence; owners and providers were not executed.");
    return;
}
if (args is ["--diagrams", var diagrams])
{
    var flows = new[] { Flows.Contracting, Flows.PaymentCollection, Flows.PaymentReconciliation, Flows.PortSubmission, Flows.ProfileProvisioning, Flows.ActivationAssessment, Flows.BillingCommencement };
    await File.WriteAllTextAsync(diagrams, "# Process diagrams\n\nGenerated by Telecom.Console --diagrams from the actual process definitions.\n\n"
        + string.Join("\n", flows.Select(p => $"## {p.Name}\n\n```mermaid\n{p.ToMermaid()}```\n")));
    return;
}
using var runtime = TelecomModule.CreateRuntime(new DeterministicProviders { LoseProvisionReply = true });
var offer = new Offer("incident-1", "customer-1", "+34600000001", 1, "profile-1", 25m);
await runtime.SendAsync(new ContractSubscription(offer));
await runtime.PublishAsync(new PortConfirmedV1(offer.SubscriptionId, offer.Msisdn, offer.Epoch,
    new DateTimeOffset(2026, 10, 26, 2, 0, 0, TimeSpan.Zero), new DateTimeOffset(2026, 10, 26, 4, 0, 0, TimeSpan.Zero)));
await runtime.PublishAsync(new PortCompletedV1(offer.SubscriptionId, offer.Msisdn, offer.Epoch));
await runtime.AdvanceAsync(31.Minutes);
var history = runtime.HistoryOf(Flows.ProfileProvisioning, Flows.ProfileKey(offer.SubscriptionId, offer.ProfileId, 1));
foreach (var entry in runtime.Journal) Console.WriteLine(entry);
Console.WriteLine($"Before recovery: {runtime.View<CustomerProgress>(offer.SubscriptionId)!.Stage}");
if (args is ["--record", var output]) await File.WriteAllTextAsync(output, history.ToJson());
(await Urd.ReplayAsync(TelecomModule.CreateRuntime, Flows.ProfileProvisioning, history)).ThrowIfDiverged();
await runtime.SendAsync(new AssignProfile(offer.SubscriptionId, offer.CustomerId, "profile-2", 2));
await runtime.PublishAsync(new ConnectivityVerifiedV1(offer.SubscriptionId, offer.ProfileId, 1));
await runtime.PublishAsync(new ConnectivityVerifiedV1(offer.SubscriptionId, "profile-2", 2));
// The simulator loses the replacement's first provision reply too; its retry consumes the parked probe.
await runtime.AdvanceAsync(1.Minutes);
Console.WriteLine($"After recovery: {runtime.View<CustomerProgress>(offer.SubscriptionId)!.Stage}");
